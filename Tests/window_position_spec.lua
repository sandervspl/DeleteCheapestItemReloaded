local Helpers = dofile("Tests/helpers.lua")

for _, client in ipairs(Helpers.clients) do
    describe(client.name .. " window position", function()
        it("keeps a dragged position through refreshes, context changes, hiding and reload", function()
            local env = Helpers.loadAddon({ client = client })
            env.putItem(0, 1, 10)
            env.MerchantFrame:Show()
            env.SlashCmdList.DCI()
            assert.equals(env.MerchantFrame, env.DCIFrame.point[2])
            env.DCI_DragFrame:Fire("OnMouseDown", "LeftButton")
            -- Model the screen anchor produced by native StartMoving.
            env.DCIFrame:SetPoint("TOPLEFT", env.UIParent, "TOPLEFT", 320, -180)
            env.addon.UpdateDCIFrame(false)
            assert.equals(320, env.DCIFrame.point[4])
            env.DCI_DragFrame:Fire("OnMouseUp", "LeftButton")
            env.fire("BAG_UPDATE", 0)
            env.MerchantFrame:Hide()
            env.LootFrame:Show()
            env.addon.UpdateDCIFrame()
            assert.equals(env.UIParent, env.DCIFrame.point[2])
            assert.equals(320, env.DCIFrame.point[4])
            env.LootFrame:Hide()
            env.addon.UpdateDCIFrame()
            assert.equals(-180, env.DCIFrame.point[5])
            local reloaded = Helpers.loadAddon({ client = client, saved = env.DCI_DB })
            reloaded.MerchantFrame:Show()
            reloaded.addon.UpdateDCIFrame()
            assert.equals(reloaded.UIParent, reloaded.DCIFrame.point[2])
            assert.equals(320, reloaded.DCIFrame.point[4])
            assert.equals(-180, reloaded.DCIFrame.point[5])
            reloaded.addon.InitializeSavedVariables(true)
            reloaded.addon.UpdateDCIFrame()
            assert.equals(reloaded.MerchantFrame, reloaded.DCIFrame.point[2])
        end)

        it("finishes and saves a drag when the window hides before mouse release", function()
            local env = Helpers.loadAddon({ client = client })
            env.SlashCmdList.DCI()
            env.DCI_DragFrame:Fire("OnMouseDown", "LeftButton")
            env.DCIFrame:SetPoint("BOTTOMRIGHT", env.UIParent, "BOTTOMRIGHT", -100, 200)
            env.DCIFrame:Hide()
            assert.is_false(env.addon.WindowDragging)
            assert.equals(-100, env.DCI_DB.WindowPosition.x)
            env.MerchantFrame:Show()
            env.addon.UpdateDCIFrame()
            assert.equals(200, env.DCIFrame.point[5])
        end)
    end)
end
