local Helpers = dofile("Tests/helpers.lua")

for _, client in ipairs(Helpers.clients) do
    describe(client.name .. " window resizing", function()
        it("preserves a resized loot window through bag updates, display changes, hiding and reload", function()
            local env = Helpers.loadAddon({ client = client })
            env.addItem(10, 1, { name = "An unusually long item name that needs a wider window" })
            env.putItem(0, 1, 10)
            env.SlashCmdList.DCI()
            local frame = env.DCIFrame
            local grip = frame.ResizeGrip
            grip:Fire("OnMouseDown", "RightButton")
            assert.is_nil(frame.sizing)
            grip:Fire("OnMouseDown", "LeftButton")
            assert.equals("BOTTOMRIGHT", frame.sizing)
            frame:SetSize(520, 400)
            frame:SetPoint("TOPLEFT", env.UIParent, "TOPLEFT", 100, -100)
            local expandedNameWidth = env.DCI_ItemInfo_TextTopLeft1.width
            env.fire("BAG_UPDATE", 0)
            assert.equals(520, frame.width)
            assert.equals(400, frame.height)
            assert.equals(100, frame.point[4])
            assert.is_truthy(env.DCI_ItemInfo_TextTopLeft1.text:find(env.items[10].name, 1, true))
            grip:Fire("OnMouseUp", "LeftButton")
            assert.is_nil(frame.sizing)
            assert.equals(520, env.DCI_DB.WindowSize.width)
            env.DCI_Config_Checkbox_ShowFullStackValues:SetChecked(true)
            env.DCI_Config_Checkbox_ShowFullStackValues:Fire("OnClick")
            assert.equals(700, frame.width)
            assert.equals(400, frame.height)
            env.DCI_Config_Checkbox_ShowFullStackValues:SetChecked(false)
            env.DCI_Config_Checkbox_ShowFullStackValues:Fire("OnClick")
            frame.CloseButton:Fire("OnClick")
            env.SlashCmdList.DCI()
            assert.equals(520, frame.width)
            assert.equals(expandedNameWidth, env.DCI_ItemInfo_TextTopLeft1.width)
            local reloaded = Helpers.loadAddon({ client = client, saved = env.DCI_DB })
            reloaded.SlashCmdList.DCI()
            assert.equals(520, reloaded.DCIFrame.width)
            assert.equals(400, reloaded.DCIFrame.height)
            frame.ResizeGrip:Fire("OnMouseDown", "LeftButton")
            frame:SetSize(1, 1) -- Model a native drag against the configured bounds.
            assert.is_true(frame.width >= 290)
            assert.is_true(frame.height >= 200)
            assert.is_true(env.DCI_ItemInfo_TextTopLeft1.width < expandedNameWidth)
            frame.ResizeGrip:Fire("OnMouseUp", "LeftButton")
        end)

        it("resizes a long ignore list, saves an interrupted resize, and restores defaults for both windows", function()
            local env = Helpers.loadAddon({ client = client })
            for id = 1, 20 do
                env.addItem(id, id)
                env.addon.SaveIgnoredItem(id)
            end
            env.SlashCmdList.DCI()
            env.SlashCmdList.DCI("ignored")
            local frame = env.addon.IgnoredItemsFrame
            local nameWidth = frame.rows[1].label.width
            if frame.NineSlice then
                assert.is_true(frame.ResizeGrip:GetFrameLevel() > frame.NineSlice:GetFrameLevel())
            end
            frame.ResizeGrip:Fire("OnMouseDown", "LeftButton")
            frame:SetSize(550, 440)
            assert.is_true(frame.rows[1].label.width > nameWidth)
            frame.scroll:SetVerticalScroll(300)
            frame.rows[15].remove:Fire("OnClick")
            assert.is_false(env.addon.IsItemIgnored(15))
            assert.equals(550, frame.width)
            frame.CloseButton:Fire("OnClick") -- Mouse release may never reach a hidden grip.
            assert.is_false(frame.DCI_Resizing)
            assert.is_nil(frame.sizing)
            env.SlashCmdList.DCI("ignored")
            assert.equals(550, frame.width)
            assert.equals(440, frame.height)
            local reloaded = Helpers.loadAddon({ client = client, saved = env.DCI_DB })
            reloaded.SlashCmdList.DCI("ignored")
            assert.equals(550, reloaded.addon.IgnoredItemsFrame.width)
            assert.equals(440, reloaded.addon.IgnoredItemsFrame.height)
            env.DCIFrame.ResizeGrip:Fire("OnMouseDown", "LeftButton")
            env.DCIFrame:SetSize(500, 500)
            env.DCIFrame.ResizeGrip:Fire("OnMouseUp", "LeftButton")
            env.DCI_Config_Button_ResetDefau:Fire("OnClick")
            assert.is_nil(env.DCI_DB.WindowSize)
            assert.is_nil(env.DCI_DB.IgnoredWindowSize)
            assert.equals(310, frame.width)
            assert.equals(286, frame.height)
            assert.equals(290, env.DCIFrame.width)
            assert.equals(240, env.DCIFrame.height)
        end)
    end)
end
